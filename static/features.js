function offerVisual(offer, name = "") {
  const label = name || offer?.name || "";
  return `<div class="product-visual">${icon(productIcon(label))}${offer?.image_url ? `<img class="product-photo" data-product-image src="/api/image?id=${encodeURIComponent(offer.id)}" alt="" loading="lazy" decoding="async">` : ""}</div>`;
}
