function purchaseModal(item, choice = null) {
  const selected =
    choice?.offer?.store ||
    state.profile.reference_store ||
    state.stores.find((s) => state.profile.stores[s.id]?.enabled)?.id;
  const day = state.month === thisMonth() ? today() : state.month + "-01";
  openModal(
    ft("purchase"),
    `<form id="purchase-form"><p><b>${esc(item.name)}</b></p><div class="form-grid"><div class="field"><label for="purchase-store">${t("stores")}</label><select id="purchase-store" name="store">${state.stores
      .filter((s) => state.profile.countries.includes(s.country))
      .map(
        (s) =>
          `<option value="${s.id}" ${s.id === selected ? "selected" : ""}>${esc(s.name)}</option>`,
      )
      .join(
        "",
      )}</select></div>${field("paid", ft("paid"), choice ? (choice.cost_cents / 100).toFixed(2) : "", "number", 'required min="0" max="100000" step="0.01"')}${field("quantity", ft("quantity"), item.quantity, "number", 'required min="0.001" max="10000" step="0.001"')}${field("purchased_on", ft("purchaseDate"), day, "date", `required max="${today()}"`)}${field("reference_price", ft("referencePrice"), "", "number", 'min="0" max="100000" step="0.01"')}</div><p class="notice">${ft("referenceHint")}</p><p class="muted">${ft("referenceStore")}: <b>${state.profile.reference_store ? esc(storeName(state.profile.reference_store)) : ft("chooseStore")}</b></p><div class="auth-error" id="purchase-error" role="alert"></div><div class="form-actions"><button type="button" data-cancel>${t("cancel")}</button><button class="primary" type="submit">${ft("recordPurchase")}</button></div></form>`,
  );
  $("#purchase-form").onsubmit = async (e) => {
    e.preventDefault();
    const data = Object.fromEntries(new FormData(e.target));
    Object.assign(data, {
      id: newId(),
      item_id: item.id,
      offline: state.offline,
    });
    try {
      if (state.offline) {
        await queueMutation("POST", "/purchases", data);
        item.checked = true;
        saveSnapshot();
        $("#modal").close();
        render();
        toast(ft("pending"));
        return;
      }
      await api("/purchases", "POST", data);
      item.checked = true;
      $("#modal").close();
      await loadSavings();
      saveSnapshot();
      render();
      loadPlan();
      toast(ft("purchaseRecorded"));
    } catch (err) {
      $("#purchase-error").textContent = err.message;
    }
  };
}
