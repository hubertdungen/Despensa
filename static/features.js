async function loadNearby(force = false) {
  if (state.offline || !state.user || nearbyLoading) return;
  const signature = JSON.stringify([
    state.profile.home_coords,
    state.profile.work_coords,
    state.profile.countries,
  ]);
  if (!force && signature === nearbySignature) return;
  nearbySignature = signature;
  nearbyLoading = true;
  if ($("#nearby-content")) $("#nearby-content").innerHTML = renderNearby();
  try {
    state.nearby = (await api("/nearby")).nearby;
  } catch {
    state.nearby = { status: "unavailable", stores: [] };
  } finally {
    nearbyLoading = false;
    if ($("#nearby-content")) {
      $("#nearby-content").innerHTML = renderNearby();
      bindFeatureActions();
    }
  }
}
async function resolveRoutine(profile) {
  const unresolved = [];
  for (const key of ["home", "work"]) {
    if (!profile[key]?.trim() || profile[key + "_coords"]) continue;
    let r;
    try { r = await api("/geocode?q=" + encodeURIComponent(profile[key])); }
    catch { unresolved.push(key); continue; }
    if (!r.results.length) { unresolved.push(key); continue; }
    const result =
      r.results.length === 1
        ? r.results[0]
        : await new Promise((resolve) => {
            let chosen = false;
            openModal(
              t("chooseLocation"),
              `<p class="muted">${t(key)}: ${esc(profile[key])}</p><div class="plan-products">${r.results.map((place, i) => `<button type="button" class="quiet" data-routine-place="${i}">${icon("pin")}${esc(place.label)}</button>`).join("")}</div>`,
            );
            $("#modal").addEventListener(
              "close",
              () => {
                if (!chosen) resolve(null);
              },
              { once: true },
            );
            $("#modal")
              .querySelectorAll("[data-routine-place]")
              .forEach(
                (b) =>
                  (b.onclick = () => {
                    chosen = true;
                    resolve(r.results[+b.dataset.routinePlace]);
                    $("#modal").close();
                  }),
              );
          });
    if (result) {
      profile[key] = result.label;
      profile[key + "_coords"] = result.coords;
      $("#f-" + key).value = result.label;
    } else unresolved.push(key);
  }
  return unresolved;
}

