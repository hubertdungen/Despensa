function setupManualConditions() {
  const store = $("#f-store"),
    condition = $("#f-condition");
  const update = () => {
    const capability = state.stores.find((s) => s.id === store.value);
    const values = [
      "public",
      ...(capability?.loyalty ? ["card", "coupon"] : []),
      ...(capability?.professional ? ["professional"] : []),
    ];
    condition.innerHTML = values
      .map((c) => `<option value="${c}">${conditionLabel(c)}</option>`)
      .join("");
    $("#f-coupon").closest(".field").hidden = true;
  };
  store.addEventListener("change", update);
  condition.addEventListener("change", () => {
    $("#f-coupon").closest(".field").hidden = condition.value !== "coupon";
  });
  update();
}

function researchState(sid) {
  const progress = state.status.jobs
    ?.find((j) => ["queued", "running"].includes(j.status))
    ?.data?.sources?.find((s) => s.store === sid);
  return progress || state.status.sources?.[sid] || { status: "pending" };
}
function researchLabel(sid) {
  const s = researchState(sid);
  if (
    !(s.count || s.catalogue_count) &&
    (s.errors?.includes("access_restricted") ||
      s.errors?.includes("robots_restricted"))
  )
    return ft("researchBlocked");
  return ft(
    {
      ok: "researchOk",
      partial: "researchPartial",
      discovering: "researchDiscovery",
      unavailable: "researchFailed",
      researching: "researchRunning",
    }[s.status] || "researchPending",
  );
}
function renderRadar(expanded = false) {
  const stores = state.stores.filter((s) =>
    state.profile.countries.includes(s.country),
  );
  const row = (s) => {
    const r = researchState(s.id);
    return `<div class="source-row"><div class="store-mark">${esc(s.name.slice(0, 2).toUpperCase())}</div><div><div class="store-name">${esc(s.name)} · ${s.country}</div><small>${researchLabel(s.id)}</small>${r.indexed ? `<small>${expanded ? `${r.indexed} ${ft("indexed")} · ` : ""}${r.catalogue_count || 0} ${ft("observations")}</small>` : ""}${
      expanded && r.methods?.length
        ? `<small>${r.methods
            .map((m) =>
              ft(
                {
                  retailer_tiles: "methodTiles",
                  product_jsonld: "methodStructured",
                  product_jsonld_displayed_price: "methodStructured",
                  embedded_catalogue: "methodEmbedded",
                  official_sitemap: "methodMap",
                  product_microdata: "methodMicro",
                }[m] || "methodStructured",
              ),
            )
            .filter((v, i, a) => a.indexOf(v) === i)
            .join(" · ")}</small>`
        : ""
    }${expanded && r.retry_at ? `<small>${ft("retry")}: ${new Date(r.retry_at * 1000).toLocaleString(locale, { hour: "2-digit", minute: "2-digit", day: "numeric", month: "short" })}</small>` : ""}</div></div>`;
  };
  return (
    stores
      .slice(0, expanded ? stores.length : 3)
      .map(row)
      .join("") +
    (!expanded && stores.length > 3
      ? `<details><summary>${ft("showMore")} (${stores.length - 3})</summary>${stores.slice(3).map(row).join("")}</details>`
      : "")
  );
}

