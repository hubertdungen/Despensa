function renderComparisonProducts() {
  const groups = (state.comparisons || [])
    .map((g) => ({
      ...g,
      offers: g.offers.filter(
        (o) => !state.storeFilter || o.store === state.storeFilter,
      ),
    }))
    .filter((g) => g.offers.length);
  if (!groups.length)
    return empty(
      "noResults",
      "noResultsText",
      `<p class="muted">${ft("researchWait")}</p>`,
    );
  return `<div class="comparison-grid">${groups
    .map((group) => {
      const best =
        group.offers.find((o) => o.id === group.best_id) || group.offers[0];
      return `<article class="comparison-card"><header><div>${offerVisual(best)}<h2>${esc(group.label)}</h2><span class="muted">${group.store_count} ${ft("inStores")}</span></div>${!group.same_reference ? `<button type="button" class="primary small" data-group="${esc(group.key)}">${icon("plus")}${ft("useFamily")}</button>` : ""}</header>${!group.same_reference ? `<p class="comparison-hint">${ft("family")}</p>` : ""}${group.saving_per_unit_cents > 0 ? `<div class="comparison-benefit"><b>${ft("saveUpTo")} ${money(group.saving_per_unit_cents)} / ${esc(group.unit)} (${group.saving_percent}%)</b><small>${ft("comparedWith")}</small></div>` : ""}<div class="comparison-rows">${group.offers
        .slice(0, 4)
        .map((o) => comparisonRow(o, group.best_id))
        .join("")}${
        group.offers.length > 4
          ? `<details><summary>${ft("showMore")} (${group.offers.length - 4})</summary>${group.offers
              .slice(4)
              .map((o) => comparisonRow(o, group.best_id))
              .join("")}</details>`
          : ""
      }</div></article>`;
    })
    .join("")}</div>`;
}

let itemSuggestionTimer;
let itemSuggestionSequence = 0;
function setupItemSuggestions(d) {
  const input = $("#f-name"),
    target = $("#item-suggestions");
  const search = async () => {
    const seq = ++itemSuggestionSequence;
    if (input.value.trim().length < 2) {
      target.innerHTML = `<span class="muted">${ft("suggestionsHint")}</span>`;
      return;
    }
    try {
      const r = await api("/offers?q=" + encodeURIComponent(input.value));
      if (seq !== itemSuggestionSequence || $("#f-name") !== input) return;
      const groups = (r.comparisons || [])
        .filter((g) => !g.same_reference)
        .slice(0, 5);
      target.innerHTML = `<span class="eyebrow">${ft("suggestions")}</span><div class="suggestion-options">${groups.map((g, i) => `<button type="button" class="suggestion" data-suggestion="${i}"><span>${esc(g.label)}</span><small>${g.store_count} ${ft("inStores")}</small></button>`).join("")}</div>`;
      target.querySelectorAll("[data-suggestion]").forEach(
        (button) =>
          (button.onclick = () => {
            const group = groups[+button.dataset.suggestion];
            d.family = group.key;
            d.offer_id = "";
            input.value = group.label;
            $("#f-query").value = group.query;
            $("#f-unit").value = group.unit;
            target
              .querySelectorAll(".suggestion")
              .forEach((b) => b.classList.toggle("selected", b === button));
          }),
      );
    } catch {
      target.innerHTML = `<span class="muted">${t("offline")}</span>`;
    }
  };
  input.addEventListener("input", () => {
    d.family = "";
    d.offer_id = "";
    clearTimeout(itemSuggestionTimer);
    itemSuggestionTimer = setTimeout(search, 220);
  });
  $("#f-query").addEventListener("input", () => {
    d.family = "";
    d.offer_id = "";
  });
  search();
}

let nearbyLoading = false;
let nearbySignature = "";
function nearbyMapLink(store) {
  return `https://www.openstreetmap.org/?mlat=${store.coords[1]}&mlon=${store.coords[0]}#map=17/${store.coords[1]}/${store.coords[0]}`;
}
function renderNearby() {
  const n = state.nearby;
  let body = "";
  if (nearbyLoading) body = `<p class="muted">${ft("searching")}</p>`;
  else if (!n || n.status === "locations_required")
    body = `<p class="muted">${ft("locationsRequired")}</p>`;
  else if (n.status !== "ok")
    body = `<p class="muted">${ft("nearbyFailed")}</p>`;
  else
    body = `<p class="tag ${n.distance_method === "road" ? "" : "amber"}">${ft(n.distance_method === "road" ? "road" : "straight")}</p><div class="nearby-grid">${[
      ["home_km", "homeNear"],
      ["work_km", "workNear"],
    ]
      .map(([axis, label]) => {
        const stores = n.stores
          .filter((s) => s[axis] != null)
          .sort((a, b) => a[axis] - b[axis])
          .slice(0, 6);
        return `<section><h3>${ft(label)}</h3>${stores.map((s) => `<div class="nearby-row"><div><strong>${esc(s.name)}</strong><small>${esc(s.address || s.country)}</small><small>${s[axis]} km${s.detour_km != null ? ` · ${ft("detour")}: ${s.detour_km} km` : ""}</small><a href="${nearbyMapLink(s)}" target="_blank" rel="noopener">${ft("map")} ↗</a></div><button type="button" class="quiet small" data-use-store="${esc(s.store)}">${icon("plus")}${ft("useStore")}</button></div>`).join("") || `<p class="muted">${ft("noStores")}</p>`}</section>`;
      })
      .join("")}</div>`;
  return `<h2 class="settings-title">${ft("nearby")}</h2><p class="muted">${ft("nearbyHint")}</p>${body}${n?.partial ? `<p class="muted">${ft("coverage")}</p>` : ""}<p class="privacy-note"><a href="https://www.openstreetmap.org/copyright" target="_blank" rel="noopener">© OpenStreetMap contributors</a> · Overpass · OSRM</p>`;
}
async function loadNearby(force = false) {
  if (state.offline || !state.user || nearbyLoading) return;
  const signature = JSON.stringify([
    state.profile.home_coords,
    state.profile.work_coords,
    state.profile.countries,
  ]);
  if (!force && signature === nearbySignature) return;
  nearbySignature = signature;
  nearbyLoading = true;
  if ($("#nearby-content")) $("#nearby-content").innerHTML = renderNearby();
  try {
    state.nearby = (await api("/nearby")).nearby;
  } catch {
    state.nearby = { status: "unavailable", stores: [] };
  } finally {
    nearbyLoading = false;
    if ($("#nearby-content")) {
      $("#nearby-content").innerHTML = renderNearby();
      bindFeatureActions();
    }
  }
}
async function resolveRoutine(profile) {
  for (const key of ["home", "work"]) {
    if (!profile[key]?.trim() || profile[key + "_coords"]) continue;
    const r = await api("/geocode?q=" + encodeURIComponent(profile[key]));
    if (!r.results.length) continue;
    const result =
      r.results.length === 1
        ? r.results[0]
        : await new Promise((resolve) => {
            let chosen = false;
            openModal(
              t("chooseLocation"),
              `<p class="muted">${t(key)}: ${esc(profile[key])}</p><div class="plan-products">${r.results.map((place, i) => `<button type="button" class="quiet" data-routine-place="${i}">${icon("pin")}${esc(place.label)}</button>`).join("")}</div>`,
            );
            $("#modal").addEventListener(
              "close",
              () => {
                if (!chosen) resolve(null);
              },
              { once: true },
            );
            $("#modal")
              .querySelectorAll("[data-routine-place]")
              .forEach(
                (b) =>
                  (b.onclick = () => {
                    chosen = true;
                    resolve(r.results[+b.dataset.routinePlace]);
                    $("#modal").close();
                  }),
              );
          });
    if (result) {
      profile[key] = result.label;
      profile[key + "_coords"] = result.coords;
      $("#f-" + key).value = result.label;
    }
  }
}

